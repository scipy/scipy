def gauss_legendre(n, mu=False):
    """Gauss-Legendre abscissae and weights for the n-point rule on [-1, 1].

    Parameters
    ----------
    n : int
        Number of quadrature points (positive).
    mu : bool, optional
        If True, also return ``mu``, as in ``scipy.special.roots_legendre``.

    Returns
    -------
    x, w : np.ndarray
        Abscissae (ascending) and weights, each of length ``n``. The weights
        are normalised to sum to 2 (to within rounding error).
    mu : float
        The integral of the weight function over [-1, 1], which is the
        constant 2.0. Only returned if ``mu`` is True.
    """
    _n = int(n)
    if n < 1 or n != _n:
        raise ValueError("n must be a positive integer.")

    n = _n
    m = n // 2  # number of nodes strictly in the negative half
    odd = n % 2

    if n <= 100:
        # positive half, descending; mirrored below so the rule is exactly symmetric
        xh, wh = _tabulated_half(n)
        centre_w = 2.0 / _CL[n] ** 2
    else:
        # nodes of the negative half (ascending) plus, for odd n, the middle one
        xa, wa = _asymptotic_half(n, m + odd)
        xh, wh = -xa[:m], wa[:m]
        centre_w = wa[m] if odd else None

    if odd:
        x = np.concatenate((-xh, [0.0], xh[::-1]))
        w = np.concatenate((wh, [centre_w], wh[::-1]))
    else:
        x = np.concatenate((-xh, xh[::-1]))
        w = np.concatenate((wh, wh[::-1]))

    # normalise so the weights sum to mu0 exactly, as the previous
    # implementation of roots_legendre did.
    mu0 = 2.0
    w *= mu0 / w.sum()
    return (x, w, mu0) if mu else (x, w)


