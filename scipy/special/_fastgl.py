# are stored consecutively, ordered outwards from x = 0. Rule sizes h = 1..h_max
# are concatenated, so the slice for size h starts at h * (h - 1) / 2.


def _tabulated_half(n):
    """Positive abscissae (descending) and weights for n <= 100."""
